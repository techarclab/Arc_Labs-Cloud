/**
 * The Arduino sketch generator (pure, no browser APIs), so CI can compile its output: see the firmware-build job.
 * Sensor fields become add() lines, control fields become onControl() handlers.
 */
import type { Device, MetricDef } from './api';

export const DEFAULT_HOST = 'mqtt.arcloud.arclabs.in';

/** C string literal: escapes what could break out of the quotes. */
const cstr = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/[\r\n]/g, ' ')}"`;
/** A comment line can't contain the end-of-comment marker. */
const ccomment = (s: string) => s.replace(/\*\//g, '* /').replace(/[\r\n]/g, ' ');

export function arduinoSketch(opts: {
  device: Device;
  channelName?: string;
  fields: MetricDef[];
  token?: string;
  provisioned: boolean;
  host: string;
  port: number;
  topicBase: string;
}) {
  const { device, fields, token, provisioned, host, port, topicBase } = opts;
  const data = fields.filter((f) => f.kind !== 'control').sort((a, b) => a.position - b.position);
  const controls = fields.filter((f) => f.kind === 'control').sort((a, b) => a.position - b.position);
  const interval = Math.max(5, device.expectedIntervalSeconds || 15);
  const hostArgs = host !== DEFAULT_HOST || port !== 8883 ? `, ${cstr(host)}, ${port}` : '';
  // Hosted ARC Cloud: the device key is all the sketch needs (the library fetches the rest). A local test server
  // spells the values out, since the library's settings request goes to the hosted API.
  const keyOnly = !hostArgs;
  const range = (f: MetricDef) =>
    [f.unit && f.unit.trim(), f.minValue != null || f.maxValue != null ? `allowed ${f.minValue ?? '…'} to ${f.maxValue ?? '…'}` : '']
      .filter(Boolean)
      .join(', ');

  const L: string[] = [];
  L.push('/*');
  L.push(` * ARC Cloud sketch for ${ccomment(`"${device.displayName}"`)}${opts.channelName ? ` (channel ${ccomment(`"${opts.channelName}"`)})` : ''}, generated by ARC Cloud.`);
  L.push(' *');
  L.push(' * 1. Arduino IDE: Sketch -> Include Library -> Add .ZIP Library... -> ArcCloud zip (link on the page you copied this from),');
  L.push(' *    and in Library Manager install "PubSubClient" and "ArduinoJson" (v7).');
  L.push(' * 2. Board: ESP32 (e.g. "ESP32 Dev Module"). Serial Monitor at 115200 baud.');
  if (provisioned) {
    L.push(' * 3. Nothing secret is in this sketch. After uploading, paste this device\'s PROVISION line (ARC Cloud -> Devices ->');
    L.push(' *    Add device or New device key -> tab "ESP32 over USB") into the Serial Monitor, line ending "New Line".');
  } else {
    L.push(' * 3. Put in your 2.4 GHz Wi-Fi below.' + (token ? '' : ' Paste the device key (arc_dk_...) you saved when the device was added'));
    if (!token) L.push(' *    (lost it? "New device key" on the device page gives a new one).');
    L.push(' *');
    L.push(' * DEVICE_KEY works like a password: anyone with it can send data as this device. Don\'t share this sketch or the');
    L.push(' * compiled file, and don\'t host this build for over-the-air updates. If it leaks: New device key.');
  }
  L.push(' * Lines marked TODO are yours to fill in. A NAN value is simply not sent, so nothing fake reaches your dashboard.');
  L.push(' */');
  L.push('#include <ArcCloud.h>');
  L.push('');
  if (!provisioned) {
    L.push(`#define WIFI_SSID      "your-wifi"`);
    L.push(`#define WIFI_PASSWORD  "your-wifi-password"`);
    if (keyOnly) {
      L.push(`#define DEVICE_KEY     ${cstr(token || 'arc_dk_paste-your-device-key-here')}`);
    } else {
      L.push(`#define DEVICE_ID      ${cstr(device.id)}`);
      L.push(`#define DEVICE_TOKEN   ${cstr(token || 'arc_dk_paste-your-device-key-here')}   // the device key`);
      L.push(`#define DEVICE_TOPIC   ${cstr(topicBase)}`);
    }
    L.push('');
  }
  L.push('ArcCloud arc;');
  L.push('');
  L.push('void setup() {');
  if (provisioned) L.push('  Serial.setRxBufferSize(2048);   // room for the PROVISION line');
  L.push('  Serial.begin(115200);');
  L.push('  // TODO: pinMode(...) and sensor setup');
  L.push('');
  L.push('  arc.setFirmwareVersion("1.0.0");');
  L.push(
    provisioned
      ? `  arc.beginProvisioned(${hostArgs.slice(2)});`
      : keyOnly
        ? '  arc.begin(WIFI_SSID, WIFI_PASSWORD, DEVICE_KEY);'
        : `  arc.begin(WIFI_SSID, WIFI_PASSWORD, DEVICE_ID, DEVICE_TOKEN, DEVICE_TOPIC${hostArgs});`,
  );
  if (controls.length) {
    L.push('');
    L.push('  // Dashboard controls. Each handler also runs right after connecting, with the control\'s current value.');
    for (const f of controls) {
      L.push(`  arc.onControl(${cstr(f.metricKey)}, [](float value) {   // ${ccomment(f.label || f.metricKey)}${range(f) ? `, ${ccomment(range(f))}` : ''}`);
      L.push(
        (f.maxValue ?? 1) <= 1
          ? `    // TODO: e.g. digitalWrite(LED_PIN, value >= 1 ? HIGH : LOW);`
          : `    // TODO: use value, e.g. analogWrite(PWM_PIN, map((long)value, ${f.minValue ?? 0}, ${f.maxValue}, 0, 255));`,
      );
      L.push('  });');
    }
  }
  L.push('');
  L.push(`  // Every ${interval} s (the device's expected interval): read, add, send as one message.`);
  L.push(`  arc.every(${provisioned ? 'arc.intervalSeconds() * 1000UL' : `${interval * 1000}UL`}, [] {`);
  if (!data.length) L.push('    // This channel has no sensor fields yet: add them in Channel settings -> Fields, then generate this again.');
  for (const f of data) {
    const expr = f.metricKey === 'rssi' ? 'WiFi.RSSI()' : 'NAN';
    const note = f.metricKey === 'rssi' ? 'measured by the board' : 'TODO: read your sensor';
    L.push(`    arc.add(${cstr(f.metricKey)}, ${expr});   // ${ccomment(f.label || f.metricKey)}${range(f) ? ` (${ccomment(range(f))})` : ''}: ${note}`);
  }
  L.push('    arc.send();');
  L.push('  });');
  L.push('}');
  L.push('');
  L.push('void loop() {');
  L.push('  arc.run();   // keep this, and avoid long delay() calls');
  L.push('}');
  return L.join('\n') + '\n';
}
