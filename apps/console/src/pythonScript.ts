/**
 * The Raspberry Pi (Linux) script generator: a complete Python 3 program for paho-mqtt, made from the channel's
 * fields (sensor fields become entries in read_sensors(), control fields become handlers). Pure, no browser APIs,
 * so tests can check that its output compiles. Follows docs/device-protocol/README.md.
 */
import type { Device, MetricDef } from './api';

/** Python string literal. JSON's escapes are all valid in Python, and it never emits a bare newline. */
const pystr = (s: string) => JSON.stringify(s);
/** A comment can't break onto a new line. */
const pycomment = (s: string) => s.replace(/[\r\n]+/g, ' ');
/** Python identifier from a field key (keys are [A-Za-z][A-Za-z0-9_]*, but stay safe). */
const ident = (s: string) => s.replace(/[^A-Za-z0-9_]/g, '_').replace(/^(?=\d)/, '_');

/** Linux boards get this script; microcontrollers get the Arduino sketch. */
export const isLinuxDevice = (deviceType: string) => deviceType === 'raspberry-pi' || deviceType === 'gateway';

export function pythonScript(opts: {
  device: Device;
  channelName?: string;
  fields: MetricDef[];
  token?: string;
  host: string;
  port: number;
  topicBase: string;
}) {
  const { device, fields, token, host, port, topicBase } = opts;
  const data = fields.filter((f) => f.kind !== 'control').sort((a, b) => a.position - b.position);
  const controls = fields.filter((f) => f.kind === 'control').sort((a, b) => a.position - b.position);
  const interval = Math.max(5, device.expectedIntervalSeconds || 15);
  const range = (f: MetricDef) =>
    [f.unit && f.unit.trim(), f.minValue != null || f.maxValue != null ? `allowed ${f.minValue ?? '…'} to ${f.maxValue ?? '…'}` : '']
      .filter(Boolean)
      .join(', ');

  const L: string[] = [];
  L.push('#!/usr/bin/env python3');
  L.push(`# ARC Cloud script for ${pycomment(`"${device.displayName}"`)}${opts.channelName ? ` (channel ${pycomment(`"${opts.channelName}"`)})` : ''}, generated by ARC Cloud.`);
  L.push('#');
  L.push('# 1. On the Raspberry Pi (Raspberry Pi OS / Debian / Ubuntu):');
  L.push('#        sudo apt install -y python3-paho-mqtt');
  L.push('#    (or in a virtual environment: pip install "paho-mqtt>=2")');
  L.push('# 2. Fill in the lines marked TODO, then run:  python3 arc_cloud.py');
  L.push('#    To start it on boot, see the systemd example at the end of this file.');
  L.push('#');
  L.push('# DEVICE_TOKEN works like a password: anyone with it can send data as this device. Keep this file private');
  L.push('# (chmod 600), and don\'t commit it to GitHub. If it leaks: ARC Cloud -> device -> Replace password.');
  L.push('# A reading of None is simply not sent, so nothing fake reaches your dashboard.');
  L.push('');
  L.push('import json');
  L.push('import ssl');
  L.push('import time');
  L.push('import uuid');
  L.push('from datetime import datetime, timezone');
  L.push('');
  L.push('import paho.mqtt.client as mqtt');
  L.push('');
  L.push(`MQTT_HOST = ${pystr(host)}`);
  L.push(`MQTT_PORT = ${port}`);
  L.push(`DEVICE_ID = ${pystr(device.id)}`);
  L.push(`DEVICE_TOKEN = ${pystr(token || 'paste-the-device-token-here')}${token ? '' : '  # TODO: the token you saved when the device was added'}`);
  L.push(`TOPIC = ${pystr(topicBase)}`);
  L.push(`INTERVAL_SECONDS = ${interval}`);
  L.push('FIRMWARE_VERSION = "1.0.0"');
  L.push('');
  L.push('BOOT_ID = uuid.uuid4().hex[:8]   # makes every messageId unique across restarts');
  L.push('counter = 0');
  L.push('');
  L.push('');
  L.push('def read_sensors():');
  L.push('    """Return {field: number}. Use None for a reading you could not take."""');
  L.push('    # TODO: import and set up your sensor library at the top of the file.');
  if (!data.length) {
    L.push('    # This channel has no sensor fields yet: add them in Channel settings -> Fields, then generate this again.');
    L.push('    return {}');
  } else {
    L.push('    return {');
    for (const f of data) {
      L.push(`        ${pystr(f.metricKey)}: None,   # ${pycomment(f.label || f.metricKey)}${range(f) ? ` (${pycomment(range(f))})` : ''}: TODO read your sensor`);
    }
    L.push('    }');
  }
  L.push('');
  if (controls.length) {
    L.push('');
    L.push('# Dashboard controls. Each handler also runs right after connecting, with the control\'s current value.');
    for (const f of controls) {
      L.push(`def on_${ident(f.metricKey)}(value):   # ${pycomment(f.label || f.metricKey)}${range(f) ? `, ${pycomment(range(f))}` : ''}`);
      L.push(
        (f.maxValue ?? 1) <= 1
          ? '    # TODO: e.g. with gpiozero: relay.on() if value >= 1 else relay.off()'
          : '    # TODO: use value, e.g. pwm_led.value = value / ' + (f.maxValue ?? 100),
      );
      L.push(`    print(${pystr(`${f.metricKey} =`)}, value)`);
      L.push('');
      L.push('');
    }
    L.push('CONTROLS = {');
    for (const f of controls) L.push(`    ${pystr(f.metricKey)}: on_${ident(f.metricKey)},`);
    L.push('}');
  } else {
    L.push('CONTROLS = {}   # control fields (switches, sliders) from Channel settings -> Fields would go here');
  }
  L.push('');
  L.push('');
  L.push('def run_command(name, payload):');
  L.push('    """Commands from Channel settings -> Commands. Return a result dict, or raise to report an error."""');
  L.push('    # TODO: e.g. if name == "reboot": ...');
  L.push('    raise ValueError(f"unknown command {name}")');
  L.push('');
  L.push('');
  L.push('def now_iso():');
  L.push('    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")');
  L.push('');
  L.push('');
  L.push('def on_connect(client, userdata, flags, reason_code, properties):');
  L.push('    if reason_code.is_failure:');
  L.push('        print("Connection refused:", reason_code)');
  L.push('        if reason_code.value in (134, 135):   # bad user name or password / not authorized');
  L.push('            print("ARC Cloud did not accept DEVICE_ID + DEVICE_TOKEN. Use the token shown when this device was added,")');
  L.push('            print("or open the device in ARC Cloud -> Replace password, and paste the new one into DEVICE_TOKEN.")');
  L.push('            client.disconnect()   # retrying with the same token cannot work');
  L.push('            userdata["stop"] = True');
  L.push('        return');
  L.push('    print("Connected to ARC Cloud")');
  L.push('    client.subscribe(TOPIC + "/cmd", qos=1)');
  L.push('    state = {"schemaVersion": 1, "timestamp": now_iso(), "state": {"firmwareVersion": FIRMWARE_VERSION}}');
  L.push('    client.publish(TOPIC + "/state", json.dumps(state), qos=1)');
  L.push('');
  L.push('');
  L.push('def on_message(client, userdata, msg):');
  L.push('    try:');
  L.push('        m = json.loads(msg.payload)');
  L.push('    except ValueError:');
  L.push('        return');
  L.push('    if m.get("type") == "command":');
  L.push('        ack = {"commandId": m["commandId"]}');
  L.push('        try:');
  L.push('            ack.update(status="ok", result=run_command(m.get("name"), m.get("payload") or {}) or {})');
  L.push('        except Exception as e:');
  L.push('            ack.update(status="error", error=str(e)[:200])');
  L.push('        client.publish(TOPIC + "/cmd-ack", json.dumps(ack), qos=1)');
  L.push('    elif "field" in m:');
  L.push('        handler = CONTROLS.get(m["field"])');
  L.push('        if handler:');
  L.push('            handler(m.get("value"))');
  L.push('');
  L.push('');
  L.push('def send_readings(client):');
  L.push('    global counter');
  L.push('    metrics = {k: v for k, v in read_sensors().items() if isinstance(v, (int, float)) and v == v}   # drop None and NaN');
  L.push('    if not metrics:');
  L.push('        print("Nothing sent: read_sensors() returned no numbers. Fill in the TODO lines (the device shows offline until it reports).")');
  L.push('        return');
  L.push('    counter += 1');
  L.push('    message = {');
  L.push('        "schemaVersion": 1,');
  L.push('        "messageId": f"{BOOT_ID}-{counter}",');
  L.push('        "timestamp": now_iso(),');
  L.push('        "metrics": metrics,');
  L.push('        "metadata": {"firmwareVersion": FIRMWARE_VERSION},');
  L.push('    }');
  L.push('    client.publish(TOPIC + "/telemetry", json.dumps(message), qos=1)');
  L.push('');
  L.push('');
  L.push('def main():');
  L.push('    if not DEVICE_TOKEN or DEVICE_TOKEN.startswith("paste-"):');
  L.push('        raise SystemExit("Set DEVICE_TOKEN first: the token shown when this device was added (lost it? ARC Cloud -> device -> Replace password).")');
  L.push('    userdata = {"stop": False}');
  L.push('    client = mqtt.Client(mqtt.CallbackAPIVersion.VERSION2, client_id=DEVICE_ID, userdata=userdata)');
  L.push('    client.username_pw_set(DEVICE_ID, DEVICE_TOKEN)');
  L.push('    client.tls_set_context(ssl.create_default_context())   # verifies the server certificate');
  L.push('    client.on_connect = on_connect');
  L.push('    client.on_message = on_message');
  L.push('    client.reconnect_delay_set(min_delay=2, max_delay=60)   # back off after a lost connection');
  L.push('    client.connect_async(MQTT_HOST, MQTT_PORT, keepalive=60)');
  L.push('    client.loop_start()');
  L.push('    try:');
  L.push('        while not userdata["stop"]:');
  L.push('            if client.is_connected():');
  L.push('                send_readings(client)');
  L.push('            time.sleep(INTERVAL_SECONDS)');
  L.push('    except KeyboardInterrupt:');
  L.push('        pass');
  L.push('    finally:');
  L.push('        client.loop_stop()');
  L.push('        client.disconnect()');
  L.push('');
  L.push('');
  L.push('if __name__ == "__main__":');
  L.push('    main()');
  L.push('');
  L.push('# Start on boot (optional): save as /etc/systemd/system/arc-cloud.service, then');
  L.push('#   sudo systemctl enable --now arc-cloud');
  L.push('#');
  L.push('#   [Unit]');
  L.push('#   Description=ARC Cloud device');
  L.push('#   After=network-online.target');
  L.push('#   Wants=network-online.target');
  L.push('#');
  L.push('#   [Service]');
  L.push('#   ExecStart=/usr/bin/python3 /home/pi/arc_cloud.py');
  L.push('#   Restart=always');
  L.push('#   User=pi');
  L.push('#');
  L.push('#   [Install]');
  L.push('#   WantedBy=multi-user.target');
  return L.join('\n') + '\n';
}
