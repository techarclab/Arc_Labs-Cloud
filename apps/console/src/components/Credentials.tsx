import { useState } from 'react';
import { Credentials, Device } from '../api';
import { download } from '../format';
import { CopyButton, Modal } from './ui';

function configH(device: Device, c: Credentials) {
  return `// config.h for ${device.displayName} — generated by ARC Cloud
#pragma once

#define WIFI_SSID      "your-wifi"
#define WIFI_PASSWORD  "your-wifi-password"

#define MQTT_HOST        "${c.mqttHost}"   // use your computer's Wi-Fi IP when testing locally
#define MQTT_PORT        ${c.mqttPort}
#define DEVICE_ID        "${c.clientId}"
#define DEVICE_PASSWORD  "${c.password}"
#define TOPIC_TELEMETRY  "${c.topics.telemetry}"
#define TOPIC_STATE      "${c.topics.state}"
#define TOPIC_COMMANDS   "${c.topics.commands ?? ''}"
#define TOPIC_ACK        "${c.topics.commandAcks ?? ''}"

#define DEVICE_TYPE         "${device.deviceType}"   // OTA releases target this device type
#define FIRMWARE_VERSION    "1.0.0"   // MAJOR.MINOR.PATCH; bump for every release (devices refuse downgrades)
#define PUBLISH_INTERVAL_MS ${device.expectedIntervalSeconds * 1000}

// Broker certificate check. Hosted ARC Cloud: keep ARC_PUBLIC_ROOTS.
// Local Docker: paste infra/certs/out/ca.crt into DEV_CA_CERT and use DEV_CA_CERT instead.
#define BROKER_CA ARC_PUBLIC_ROOTS
static const char DEV_CA_CERT[] = R"PEM(
-----BEGIN CERTIFICATE-----
...
-----END CERTIFICATE-----
)PEM";

// OTA signing public key: node tools/firmware-sign.mjs header firmware-signing-public.pem
// Until it is set, this device refuses every firmware update.
static const char OTA_PUBLIC_KEY_PEM[] = R"PEM(
-----BEGIN PUBLIC KEY-----
...
-----END PUBLIC KEY-----
)PEM";
`;
}

/**
 * One-line provisioning payload for firmware that keeps credentials in NVS (firmware/esp32-arduino/arc_dht_mqtt):
 * pasted into the Serial Monitor over USB, so no secret is ever compiled into a (public) OTA image.
 */
function provisionLine(device: Device, c: Credentials) {
  const topicBase = c.topics.telemetry.replace(/\/telemetry$/, '');
  return `PROVISION ${JSON.stringify({
    wifiSsid: 'your-wifi',
    wifiPassword: 'your-wifi-password',
    deviceId: c.clientId,
    devicePassword: c.password,
    topicBase,
    intervalSeconds: device.expectedIntervalSeconds,
  })}`;
}

/** Shown once after a device is created or its password is replaced. */
export function CredentialsDialog({ device, credentials, onClose, replaced }: { device: Device; credentials: Credentials; onClose: () => void; replaced?: boolean }) {
  const [tab, setTab] = useState<'usb' | 'file' | 'esp32' | 'http' | 'details'>('usb');
  const [saved, setSaved] = useState(false);
  const fileName = `${device.displayName.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'device'}.json`;

  return (
    <Modal
      open
      wide
      onClose={() => (saved || confirm('Close without saving the password? You won’t be able to see it again.')) && onClose()}
      title={replaced ? `New password for ${device.displayName}` : `${device.displayName} is registered`}
      footer={
        <button className="btn primary" onClick={() => (saved || confirm('Close without saving the password? You won’t be able to see it again.')) && onClose()}>
          Done
        </button>
      }
    >
      <div className="note">
        Save this password now. ARC Cloud only stores a scrambled version of it, so it can’t be shown again. If you lose it, replace it from the device page.
        {replaced && ' The old password has stopped working.'}
      </div>

      <div className="tabs" role="tablist">
        {(
          [
            ['usb', 'ESP32 over USB'],
            ['file', 'For the simulator'],
            ['esp32', 'config.h (arc_device)'],
            ['http', 'HTTP API'],
            ['details', 'All details'],
          ] as const
        ).map(([k, label]) => (
          <button key={k} role="tab" aria-selected={tab === k} onClick={() => setTab(k)}>
            {label}
          </button>
        ))}
      </div>

      {tab === 'usb' && (
        <>
          <p>
            For <code>arc_dht_mqtt</code> and other firmware that stores its credentials on the device: flash the firmware, open the Serial Monitor (115200
            baud, line ending “New Line”), replace <code>your-wifi</code> and <code>your-wifi-password</code> with your 2.4&nbsp;GHz Wi-Fi, paste the line and
            press Enter. The device saves it and restarts. Nothing secret is compiled into the firmware, so the same image can be updated over the air on every
            device.
          </p>
          <pre className="code">{provisionLine(device, credentials)}</pre>
          <div className="row">
            <span onClick={() => setSaved(true)}>
              <CopyButton text={provisionLine(device, credentials)} label="Copy PROVISION line" />
            </span>
          </div>
        </>
      )}

      {tab === 'file' && (
        <>
          <p>Download the device file and put it in your <code>arc-cloud</code> folder, then run:</p>
          <pre className="code">npm run simulate -- --creds {fileName} --ca infra/certs/out/ca.crt --interval {device.expectedIntervalSeconds}</pre>
          <div className="row">
            <button
              className="btn primary"
              onClick={() => {
                download(fileName, JSON.stringify({ device, credentials }, null, 2));
                setSaved(true);
              }}
            >
              Download {fileName}
            </button>
          </div>
        </>
      )}

      {tab === 'esp32' && (
        <>
          <p>
            Save this as <code>config.h</code> next to <code>arc_device.ino</code> (in <code>firmware/esp32-arduino/arc_device</code>), then fill in your Wi-Fi and the OTA signing key.
            This file holds the device password, so a build made with it must never be hosted for OTA; prefer “ESP32 over USB”.
          </p>
          <pre className="code">{configH(device, credentials)}</pre>
          <div className="row">
            <span onClick={() => setSaved(true)}>
              <CopyButton text={configH(device, credentials)} label="Copy config.h" />
            </span>
          </div>
        </>
      )}

      {tab === 'http' && credentials.http && (
        <>
          <p>
            Like ThingSpeak: send readings with a web request. The device’s password is its API key; send it in the <code>Authorization</code> header, not in the URL (URLs end up in proxy and server logs). Use your computer’s Wi-Fi address instead of <code>localhost</code> when calling from an ESP32.
          </p>
          <dl className="secret">
            <dt>API key</dt>
            <dd>{credentials.http.apiKey}</dd>
            <span onClick={() => setSaved(true)}>
              <CopyButton text={credentials.http.apiKey} />
            </span>
            <dt>Send data</dt>
            <dd>{`curl -H "Authorization: Bearer ${credentials.http.apiKey}" "${credentials.http.updateUrl}?field1=25.4"`}</dd>
            <span onClick={() => setSaved(true)}>
              <CopyButton text={`curl -H "Authorization: Bearer ${credentials.http.apiKey}" "${credentials.http.updateUrl}?field1=25.4"`} />
            </span>
            <dt>Read controls</dt>
            <dd>{`curl -H "Authorization: Bearer ${credentials.http.apiKey}" "${credentials.http.controlsUrl}"`}</dd>
            <span onClick={() => setSaved(true)}>
              <CopyButton text={`curl -H "Authorization: Bearer ${credentials.http.apiKey}" "${credentials.http.controlsUrl}"`} />
            </span>
          </dl>
          <p className="small muted">The ESP32 example for HTTP is in <code>firmware/esp32-arduino/arc_http</code>.</p>
        </>
      )}

      {tab === 'details' && (
        <dl className="secret">
          {(
            [
              ['Server', `${credentials.mqttHost}:${credentials.mqttPort} (TLS)`],
              ['Client ID', credentials.clientId],
              ['Username', credentials.username],
              ['Password', credentials.password],
              ['Data topic', credentials.topics.telemetry],
              ['State topic', credentials.topics.state],
              ...(credentials.topics.commands ? ([['Control topic', credentials.topics.commands]] as const) : []),
            ] as const
          ).map(([k, v]) => (
            <div key={k} style={{ display: 'contents' }}>
              <dt>{k}</dt>
              <dd>{v}</dd>
              <span onClick={() => k === 'Password' && setSaved(true)}>
                <CopyButton text={v} />
              </span>
            </div>
          ))}
        </dl>
      )}
    </Modal>
  );
}
